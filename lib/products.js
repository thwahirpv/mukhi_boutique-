export function formatPrice(amount) {
  if (typeof amount !== "number") return amount;
  return new Intl.NumberFormat("en-IN", {
    style: "currency",
    currency: "INR",
    maximumFractionDigits: 0
  }).format(amount);
}

export function generateWhatsAppMessageText({
  product,
  color,
  variation,
  quantity = 1,
  customerName = "",
  deliveryCity = "",
  measurements = "",
  notes = "",
  productUrl = ""
}) {
  const basePrice = product.price;
  const additional = variation?.additionalPrice || 0;
  const unitPrice = basePrice + additional;
  const originalUnitPrice = product.originalPrice + additional;
  const totalPrice = unitPrice * quantity;
  const totalSavings = (originalUnitPrice - unitPrice) * quantity;
  const discountPct = product.discountPercentage || Math.round(((originalUnitPrice - unitPrice) / originalUnitPrice) * 100);

  const lines = [
    `✨ *NEW ORDER REQUEST — MUKHI BOUTIQUE* ✨`,
    `━━━━━━━━━━━━━━━━━━━━━━━━━`,
    `📦 *PRODUCT DETAILS*`,
    `• *Product:* ${product.name}`,
    `• *SKU / Ref:* ${product.sku || product.id}`,
    `• *Category:* ${product.category || "Designer Saree"}`,
    `• *Selected Color:* ${color?.name || color || "Standard Shade"}`,
    `• *Blouse / Styling:* ${variation?.label || variation?.name || variation || "Standard"}`,
    `• *Quantity:* ${quantity} piece(s)`,
    ``,
    `💰 *PRICING & SAVINGS*`,
    `• *Original Price:* ${formatPrice(originalUnitPrice)}`,
    `• *Offer Unit Price:* ${formatPrice(unitPrice)}`,
    totalSavings > 0 ? `• *Total Savings:* ${formatPrice(totalSavings)} (${discountPct}% OFF)` : null,
    `• *TOTAL ESTIMATED AMOUNT:* *${formatPrice(totalPrice)}*`,
    `━━━━━━━━━━━━━━━━━━━━━━━━━`,
  ];

  const customerDetails = [];
  if (customerName && customerName.trim()) {
    customerDetails.push(`• *Client Name:* ${customerName.trim()}`);
  }
  if (deliveryCity && deliveryCity.trim()) {
    customerDetails.push(`• *Delivery Destination:* ${deliveryCity.trim()}`);
  }
  if (measurements && measurements.trim()) {
    customerDetails.push(`• *Custom Measurements:* ${measurements.trim()}`);
  }
  if (notes && notes.trim()) {
    customerDetails.push(`• *Special Instructions:* ${notes.trim()}`);
  }

  if (customerDetails.length > 0) {
    lines.push(`👤 *CLIENT & DELIVERY DETAILS*`);
    lines.push(...customerDetails);
    lines.push(`━━━━━━━━━━━━━━━━━━━━━━━━━`);
  }

  if (productUrl) {
    lines.push(`🔗 *Product Reference:* ${productUrl}`);
    lines.push(`━━━━━━━━━━━━━━━━━━━━━━━━━`);
  }

  lines.push(
    `_Hello Mukhi Boutique team! I would like to place an order for this piece. Please share payment details (UPI/GPay/Bank transfer), dispatch timeline, and blouse measurement assistance._`
  );

  return lines.filter((l) => l !== null).join("\n");
}

export function buildWhatsAppMessage(params) {
  const text = generateWhatsAppMessageText(params);
  return encodeURIComponent(text);
}

export function getWhatsAppOrderLink(params, customPhone = null) {
  const phone = customPhone || BOUTIQUE_INFO.whatsappNumber;
  const message = buildWhatsAppMessage(params);
  return `https://wa.me/${phone}?text=${message}`;
}


